"""Quarantine losers — never delete anything.

Applying a decision moves every non-keeper file into
``<root>/_keeper_quarantine/<group-id>/`` and records a ``manifest.json``
plus a portable ``restore.sh``. ``restore()`` puts every file back exactly
where it came from and removes the quarantine scaffolding.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from .decide import Decision
from .scan import FileFact

QDIR = "_keeper_quarantine"
MANIFEST_NAME = "manifest.json"
RESTORE_SH_NAME = "restore.sh"


@dataclass
class GroupDecision:
    """One cluster plus its verdict, ready to apply or just report."""

    files: list[FileFact]
    decision: Decision

    @property
    def losers(self) -> list[FileFact]:
        return [f for f in self.files if f.path != self.decision.keep.path]


def _slug(text: str, limit: int = 32) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug[:limit].rstrip("-") or "group"


def _group_id(gd: GroupDecision) -> str:
    digest = hashlib.sha256(
        "|".join(sorted(f.rel for f in gd.files)).encode()
    ).hexdigest()[:8]
    return f"{_slug(gd.decision.keep.name)}-{digest}"


def _bash_quote(text: str) -> str:
    return "'" + text.replace("'", "'\"'\"'") + "'"


def apply_quarantine(root: Path, groups: list[GroupDecision]) -> Path | None:
    """Move losers into quarantine. Returns manifest path (or None if nothing to do)."""
    root = root.resolve()
    to_quarantine = [g for g in groups if g.losers]
    if not to_quarantine:
        return None

    qroot = root / QDIR
    qroot.mkdir(parents=True, exist_ok=True)

    manifest: dict = {
        "created": dt.datetime.now().isoformat(timespec="seconds"),
        "root": str(root),
        "groups": [],
    }
    restore_lines = [
        "#!/usr/bin/env bash",
        "# Restores files moved by Keeper. Generated by `keeper --apply`.",
        "set -euo pipefail",
        'cd "$(dirname "$0")/.."',
    ]

    for gd in to_quarantine:
        gid = _group_id(gd)
        gdir = qroot / gid
        gdir.mkdir(parents=True, exist_ok=True)

        group_entry = {
            "id": gid,
            "kept": gd.decision.keep.rel,
            "reason": gd.decision.reason,
            "method": gd.decision.method,
            "moved": [],
        }
        for fact in gd.losers:
            target = gdir / fact.name
            counter = 1
            while target.exists():
                target = gdir / f"{fact.name}.{counter}"
                counter += 1
            shutil.move(str(fact.path), str(target))
            group_entry["moved"].append(
                {"from": fact.rel, "to": str(target.relative_to(root))}
            )
            restore_lines.append(
                f"mkdir -p -- {_bash_quote(str(fact.path.parent))} && "
                f"mv -n -- {_bash_quote(str(target))} {_bash_quote(str(fact.path))}"
            )
        manifest["groups"].append(group_entry)

    manifest_path = qroot / MANIFEST_NAME
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    restore_path = qroot / RESTORE_SH_NAME
    restore_path.write_text("\n".join(restore_lines) + "\n", encoding="utf-8")
    restore_path.chmod(restore_path.stat().st_mode | 0o111)

    return manifest_path


def restore(root: Path) -> tuple[int, str | None]:
    """Undo a quarantine. Returns (files restored, error message or None)."""
    root = root.resolve()
    qroot = root / QDIR
    manifest_path = qroot / MANIFEST_NAME
    if not manifest_path.exists():
        return 0, f"no keeper quarantine found at {manifest_path}"

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    restored = 0
    errors: list[str] = []

    for group in manifest.get("groups", []):
        for entry in group.get("moved", []):
            src = root / entry["to"]
            dst = root / entry["from"]
            if not src.exists():
                errors.append(f"missing: {entry['to']}")
                continue
            dst.parent.mkdir(parents=True, exist_ok=True)
            if dst.exists():  # never clobber a file that reappeared
                errors.append(f"original spot taken, left in quarantine: {entry['from']}")
                continue
            shutil.move(str(src), str(dst))
            restored += 1

    # Remove empty group dirs, then the quarantine root itself.
    for child in sorted(qroot.rglob("*"), reverse=True):
        if child.is_dir():
            try:
                child.rmdir()
            except OSError:
                pass
    for leftover in (manifest_path, qroot / RESTORE_SH_NAME):
        if leftover.exists():
            leftover.unlink()
    try:
        qroot.rmdir()
    except OSError:
        pass

    return restored, "; ".join(errors) if errors else None
